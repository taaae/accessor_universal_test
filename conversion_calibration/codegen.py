def render() -> str:
    pieces=[HEADER]
    for i, case in enumerate(CASES): pieces.append(decoder(case,i))
    rows=[]; launches=[]; attrs=[]
    for i, case in enumerate(CASES):
        rows.append(f'  {{"{case.case_id}", "{case.split}", "{case.group}", decoder<{i}>::shared_bytes}},')
        launches.append(f"  case {i}: dot_case_kernel<{i}><<<grid,block,shared,stream>>>(left,right,count,tables,partials); break;")
        attrs.append(f"  case {i}: return cudaFuncGetAttributes(attributes, dot_case_kernel<{i}>);")
    footer = (FOOTER.replace("CASE_INFO_ROWS", "\n".join(rows))
              .replace("LAUNCH_CASES", "\n".join(launches))
              .replace("ATTRIBUTE_CASES", "\n".join(attrs)))
    return "".join(pieces) + footer


def write(output: Path, manifest_output: Path) -> None:
    text=render()
    output.parent.mkdir(parents=True,exist_ok=True)
    output.write_text(text,encoding="utf-8")
    document=manifest_document(); document["generated_header_sha256"]=hashlib.sha256(text.encode()).hexdigest()
    manifest_output.parent.mkdir(parents=True,exist_ok=True)
    manifest_output.write_text(json.dumps(document,indent=2,sort_keys=True)+"\n",encoding="utf-8")


