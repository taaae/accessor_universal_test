    parser=argparse.ArgumentParser(); parser.add_argument("--output",type=Path,default=Path("generated/conversion_calibration_cases.cuh")); parser.add_argument("--manifest",type=Path,default=Path("generated/conversion_calibration_manifest.json")); args=parser.parse_args(); write(args.output,args.manifest)


