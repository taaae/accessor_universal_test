def _base_prelude(shared_bytes: int = 0, context: str = "device_tables") -> str:
    return f"  using context = {context};\n  static constexpr std::size_t shared_bytes = {shared_bytes}u;\n  __device__ __forceinline__ static context prepare(device_tables t, unsigned char *) {{ return t; }}\n"


def _integer_body(op: str, count: int, dependency: str) -> str:
    call = {"iadd3": "op_iadd3({a}, 0x9e3779b9u + {i}u, 0x7f4a7c15u)", "lop3": "op_lop3({a}, 0xa5a5a5a5u + {i}u, 0x3c6ef372u)", "shf": "op_shf({a}, {shift}u)", "imad": "op_imad({a}, 1664525u + 2u * {i}u, 1013904223u)"}[op]
    lines: list[str] = []
    if dependency == "chain":
        lines.append("    std::uint32_t v = raw;")
        for i in range(count):
            lines.append("    v = " + call.format(a="v", i=i, shift=(i % 31) + 1) + ";")
        lines.append("    return finite_from_u32(v);")
    else:
        lines.append("    std::uint32_t v0=raw, v1=raw^0x55555555u, v2=raw^0xaaaaaaaau, v3=~raw;")
        for i in range(count):
            lane = i % 4
            lines.append(f"    v{lane} = " + call.format(a=f"v{lane}", i=i, shift=(i % 31) + 1) + ";")
        lines.append("    return finite_from_u32(v0 ^ v1 ^ v2 ^ v3);")
    return "\n".join(lines)


def _fp_body(precision: str, op: str, count: int, dependency: str) -> str:
    typ = "double" if precision == "fp64" else "float"
    seed = "finite_from_u32(raw)" if precision == "fp64" else "static_cast<float>(finite_from_u32(raw))"
